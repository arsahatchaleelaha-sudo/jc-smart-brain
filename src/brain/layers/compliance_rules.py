# ─── Compile all rules ────────────────────────────────────────────────────────


ALL_RULES = INCOME_RULES + HEALTH_RULES + MEMBER_RULES


def get_rules() -> list[dict[str, Any]]:
    """คืนรายการทั้งหมด — ใช้โดย guard layer."""
    return ALL_RULES


def apply_rules(answer: str, query: str = "") -> list[dict[str, Any]]:
    """apply rules กับคำตอบ — คืนรายการที่ triggered."""

    triggered: list[dict[str, Any]] = []
    al = answer.lower()
    ql = query.lower() if query else ""

    for rule in ALL_RULES:
        pattern = rule["pattern"]
        # เช็คว่ามี pattern นี้ในคำตอบ (หรือคำถาม)
        if re.search(pattern, al) or (query and re.search(pattern, ql)):
            triggered.append(rule)

    return triggered
